use std::collections::{BTreeMap, VecDeque};

#[derive(Clone, Debug)]
#[non_exhaustive]
pub struct Frame {
    pub pid: u32,
    pub swapchain: String,
    pub time_s: f64,
    pub frame_ms: f64,
}

#[derive(Clone, Debug, Default)]
#[non_exhaustive]
pub struct Summary {
    pub samples: usize,
    pub average_fps: Option<f64>,
    pub low_1: Option<f64>,
    pub low_01: Option<f64>,
    pub min_fps: Option<f64>,
    pub max_fps: Option<f64>,
}

#[derive(Clone, Debug, Default)]
#[non_exhaustive]
pub struct Snapshot {
    pub swapchain: String,
    pub current_fps: Option<f64>,
    pub frame_ms: Option<f64>,
    pub rolling: Summary,
    pub session: Summary,
    /// Recent individual frame intervals, never generated by the UI timer.
    pub history_ms: Vec<f64>,
}

#[derive(Default)]
struct Chain {
    samples: VecDeque<(f64, f64)>,
}

/// A bounded-duration validation session, separated by swapchain.
/// The production collector will need a streaming session distribution.
pub struct Statistics {
    window_s: f64,
    chains: BTreeMap<String, Chain>,
}

impl Statistics {
    pub fn new(window_s: f64) -> Self {
        assert!(window_s.is_finite() && window_s > 0.0);
        Self {
            window_s,
            chains: BTreeMap::new(),
        }
    }

    pub fn push(&mut self, frame: Frame) -> bool {
        if !frame.time_s.is_finite()
            || frame.time_s < 0.0
            || !frame.frame_ms.is_finite()
            || frame.frame_ms <= 0.0
        {
            return false;
        }
        let chain = self.chains.entry(frame.swapchain).or_default();
        if chain
            .samples
            .back()
            .is_some_and(|last| frame.time_s <= last.0)
            || chain.samples.len() >= 2_000_000
        {
            return false;
        }
        chain.samples.push_back((frame.time_s, frame.frame_ms));
        true
    }

    pub fn snapshot(&self) -> Snapshot {
        let end = self
            .chains
            .values()
            .filter_map(|c| c.samples.back().map(|s| s.0))
            .fold(0.0, f64::max);
        // Compare against a shared timestamp so stopped chains cannot keep winning.
        let Some((name, chain)) = self.chains.iter().max_by_key(|(_, c)| {
            c.samples
                .iter()
                .rev()
                .take_while(|s| s.0 >= end - 1.0)
                .count()
        }) else {
            return Snapshot::default();
        };
        let rolling: Vec<_> = chain
            .samples
            .iter()
            .copied()
            .filter(|s| s.0 >= end - self.window_s)
            .collect();
        let current: Vec<_> = chain
            .samples
            .iter()
            .rev()
            .take_while(|s| s.0 >= end - 1.0)
            .map(|s| s.1)
            .collect();
        let frame_ms =
            (!current.is_empty()).then(|| current.iter().sum::<f64>() / current.len() as f64);
        Snapshot {
            swapchain: name.clone(),
            current_fps: frame_ms.map(|ms| 1000.0 / ms),
            frame_ms,
            rolling: summarize(&rolling),
            session: summarize(&chain.samples.iter().copied().collect::<Vec<_>>()),
            history_ms: chain
                .samples
                .iter()
                .rev()
                .take(120)
                .map(|s| s.1)
                .collect::<Vec<_>>()
                .into_iter()
                .rev()
                .collect(),
        }
    }
}

fn summarize(samples: &[(f64, f64)]) -> Summary {
    if samples.is_empty() {
        return Summary::default();
    }
    let total_ms: f64 = samples.iter().map(|s| s.1).sum();
    let mut slowest: Vec<_> = samples.iter().map(|s| s.1).collect();
    slowest.sort_unstable_by(|a, b| b.total_cmp(a));
    let low = |fraction: f64, minimum: usize| {
        (samples.len() >= minimum).then(|| {
            let n = (samples.len() as f64 * fraction).ceil() as usize;
            1000.0 * n as f64 / slowest[..n].iter().sum::<f64>()
        })
    };
    // Exclude the first partial second and current partial second.
    let first = samples.first().unwrap().0.floor() as u64 + 1;
    let last = samples.last().unwrap().0.floor() as u64;
    let mut buckets = BTreeMap::<u64, usize>::new();
    for &(t, _) in samples {
        let bucket = t.floor() as u64;
        if bucket >= first && bucket < last {
            *buckets.entry(bucket).or_default() += 1;
        }
    }
    let values: Vec<f64> = (first..last)
        .take(601)
        .map(|b| *buckets.get(&b).unwrap_or(&0) as f64)
        .collect();
    Summary {
        samples: samples.len(),
        average_fps: Some(1000.0 * samples.len() as f64 / total_ms),
        low_1: low(0.01, 100),
        low_01: low(0.001, 1000),
        min_fps: values.iter().copied().reduce(f64::min),
        max_fps: values.iter().copied().reduce(f64::max),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    fn frame(t: f64, ms: f64, chain: &str) -> Frame {
        Frame {
            pid: 10,
            swapchain: chain.into(),
            time_s: t,
            frame_ms: ms,
        }
    }
    #[test]
    fn average_uses_elapsed_frame_time_not_mean_of_fps() {
        let s = summarize(&[(0.0, 10.0), (0.1, 30.0)]);
        assert_eq!(s.average_fps, Some(50.0));
        assert_eq!(s.low_1, None);
    }
    #[test]
    fn lows_require_enough_samples_and_average_slowest_tail() {
        let samples: Vec<_> = (0..1000)
            .map(|i| (i as f64 / 100.0, if i < 10 { 50.0 } else { 10.0 }))
            .collect();
        let s = summarize(&samples);
        assert_eq!(s.low_1, Some(20.0));
        assert_eq!(s.low_01, Some(20.0));
        assert!(summarize(&samples[..99]).low_1.is_none());
        assert!(summarize(&samples[..999]).low_01.is_none());
    }
    #[test]
    fn min_max_use_complete_seconds_and_include_idle_seconds() {
        let s = summarize(&[(0.5, 10.0), (1.1, 10.0), (1.3, 10.0), (3.1, 10.0)]);
        assert_eq!(s.min_fps, Some(0.0));
        assert_eq!(s.max_fps, Some(2.0));
    }
    #[test]
    fn rejects_bad_times_and_keeps_chains_separate() {
        let mut stats = Statistics::new(30.0);
        assert!(!stats.push(frame(1.0, f64::NAN, "A")));
        assert!(stats.push(frame(1.0, 10.0, "A")));
        assert!(!stats.push(frame(0.9, 10.0, "A")));
        stats.push(frame(1.1, 10.0, "A"));
        stats.push(frame(1.0, 100.0, "B"));
        let s = stats.snapshot();
        assert_eq!(s.swapchain, "A");
        assert_eq!(s.session.samples, 2);
        assert_eq!(s.current_fps, Some(100.0));
    }
    #[test]
    fn rolling_window_expires_old_samples_but_session_keeps_them() {
        let mut stats = Statistics::new(1.0);
        for i in 0..4 {
            stats.push(frame(i as f64, 10.0, "A"));
        }
        let s = stats.snapshot();
        assert_eq!(s.rolling.samples, 2);
        assert_eq!(s.session.samples, 4);
    }
}

#[cfg(test)]
mod regression_tests {
    use super::*;
    #[test]
    fn stopped_busy_chain_cannot_outvote_new_active_chain() {
        let mut stats = Statistics::new(30.0);
        for i in 1..100 {
            stats.push(Frame {
                pid: 42,
                swapchain: "old".into(),
                time_s: i as f64 * 0.01,
                frame_ms: 10.0,
            });
        }
        stats.push(Frame {
            pid: 42,
            swapchain: "new".into(),
            time_s: 4.0,
            frame_ms: 20.0,
        });
        assert_eq!(stats.snapshot().swapchain, "new");
    }
}
